// 曾经实现过的「登录态快照」方案（把注册表里的战网登录凭证按「账号 + 区服」
// 备份/还原）已经整体废弃，原因：
//
//   1. 战网登录凭证的唯一合法维护者是客户端本身 —— 它会在运行时持续刷新令牌
//      并写回注册表。第三方把几小时前的"冻结帧"写回去，只会更旧，
//      救不回已过期的会话，反而可能覆盖掉客户端刚刷新的新令牌。
//   2. 会话令牌是短命的，且只在客户端**运行期间**续期。本工具的切换流程会
//      关闭客户端再重启，所以凭证离开客户端后必然单向老化 —— 这是
//      "改配置 + 重启"式切换的固有代价，靠写回旧凭证无法改善。
//   3. 结论：切换频繁要求重新登录，其成因在服务端令牌策略与国服的
//      网页登录要求，本地无法绕过。
//
// 现在的做法回到"不做任何凭证搬运"，只做两件事：
//   * 切换前让战网**正常退出**（CloseMainWindow，超时才强杀），
//     给它机会把状态与刷新后的令牌好好写盘
//   * 只在必要时重写 SavedAccountNames（目标账号已在首位就不动），
//     避免无谓地重排配置而打断已有会话
//
// 详细的凭证存放位置与生效机制，见 README 的「关于战网登录状态」一节。
